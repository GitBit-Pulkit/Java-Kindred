package com.kindred.model;

import java.time.LocalDateTime;

/**
 * A Kindred member. Maps to one row of the `users` table.
 *
 * - passwordHash holds a BCrypt hash, NEVER the plain password.
 * - credits is the wallet balance (SkillCredits). MySQL has a CHECK (credits >= 0)
 *   constraint, so a balance can never go negative in the database.
 *
 * Implements Comparable<User> (by credits) so CollectionUtils.topN() can build
 * the admin leaderboard. Implements CsvExportable so users can be exported.
 */
// SYLLABUS: Generics - implements Comparable<User>, so it satisfies the bound <T extends Comparable<? super T>>
// SYLLABUS: CSV export - implements CsvExportable
public class User implements CsvExportable, Comparable<User> {

    // Note: the password hash is deliberately NOT part of the CSV export.
    public static final String CSV_HEADER = "user_id,username,full_name,role,credits,joined_on";

    private int userId;
    private String username;
    private String fullName;
    private String passwordHash;
    private Role role;
    private int credits;
    private LocalDateTime createdAt;

    /** Used when registering (the id and created_at are generated by MySQL). */
    public User(String username, String fullName, String passwordHash, Role role, int credits) {
        this.username = username;
        this.fullName = fullName;
        this.passwordHash = passwordHash;
        this.role = role;
        this.credits = credits;
    }

    /** Used by UserDao when mapping a ResultSet row into an object. */
    public User(int userId, String username, String fullName, String passwordHash,
                Role role, int credits, LocalDateTime createdAt) {
        this(username, fullName, passwordHash, role, credits);
        this.userId = userId;
        this.createdAt = createdAt;
    }

    public int getUserId()            { return userId; }
    public String getUsername()       { return username; }
    public String getFullName()       { return fullName; }
    public String getPasswordHash()   { return passwordHash; }
    public Role getRole()             { return role; }
    public int getCredits()           { return credits; }
    public LocalDateTime getCreatedAt() { return createdAt; }

    public void setUserId(int userId)             { this.userId = userId; }
    public void setFullName(String fullName)      { this.fullName = fullName; }
    public void setPasswordHash(String hash)      { this.passwordHash = hash; }
    public void setCredits(int credits)           { this.credits = credits; }

    public boolean isAdmin() {
        return role == Role.ADMIN;
    }

    @Override
    public String[] csvValues() {
        return new String[] {
                String.valueOf(userId), username, fullName, role.name(),
                String.valueOf(credits), String.valueOf(createdAt)
        };
    }

    /** Natural order = by wallet balance (used for the leaderboard). */
    @Override
    public int compareTo(User other) {
        return Integer.compare(this.credits, other.credits);
    }

    @Override
    public String toString() {
        return String.format("#%-3d %-15s %-22s %-6s %4d credits",
                userId, username, fullName, role, credits);
    }
}
